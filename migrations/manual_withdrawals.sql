CREATE TABLE IF NOT EXISTS shineray_withdrawal_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id),
    wallet_id BIGINT NOT NULL,
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa BETWEEN 1 AND 500000000),
    fee_fcfa BIGINT NOT NULL CHECK (fee_fcfa >= 0),
    net_amount_fcfa BIGINT NOT NULL CHECK (net_amount_fcfa > 0),
    wallet_snapshot JSONB NOT NULL CHECK (jsonb_typeof(wallet_snapshot) = 'object'),
    status VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    CHECK (fee_fcfa + net_amount_fcfa = amount_fcfa)
);
CREATE INDEX IF NOT EXISTS shineray_withdrawal_requests_user_idx
    ON shineray_withdrawal_requests(user_id,status);
