CREATE TABLE IF NOT EXISTS shineray_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(16) NOT NULL UNIQUE,
    password_salt BYTEA NOT NULL,
    password_hash BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT shineray_phone_format CHECK (
        phone ~ '^\+225[0-9]{10}$' OR phone ~ '^\+228[0-9]{8}$'
    )
);

CREATE TABLE IF NOT EXISTS shineray_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS shineray_sessions_user_idx
    ON shineray_sessions(user_id);

CREATE TABLE IF NOT EXISTS shineray_demo_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('recharge', 'withdrawal', 'purchase')),
    label VARCHAR(80) NOT NULL,
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa > 0 AND amount_fcfa <= 500000000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS shineray_demo_activity_user_idx
    ON shineray_demo_activity(user_id, created_at DESC);
