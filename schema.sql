CREATE TABLE IF NOT EXISTS shineray_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(16) NOT NULL UNIQUE,
    password_salt BYTEA NOT NULL,
    password_hash BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT shineray_phone_format CHECK (
        phone ~ '^\+(225|229)[0-9]{10}$' OR phone ~ '^\+(228|226|227)[0-9]{8}$'
        OR phone ~ '^\+237[0-9]{9}$'
    )
);

-- Update existing databases as well as fresh installations.
ALTER TABLE shineray_users DROP CONSTRAINT IF EXISTS shineray_phone_format;
ALTER TABLE shineray_users ADD CONSTRAINT shineray_phone_format CHECK (
    phone ~ '^\+(225|229)[0-9]{10}$' OR phone ~ '^\+(228|226|227)[0-9]{8}$'
    OR phone ~ '^\+237[0-9]{9}$'
);

CREATE TABLE IF NOT EXISTS shineray_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS shineray_sessions_user_idx
    ON shineray_sessions(user_id);

CREATE TABLE IF NOT EXISTS shineray_demo_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('recharge', 'withdrawal', 'purchase')),
    label VARCHAR(80) NOT NULL,
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa > 0 AND amount_fcfa <= 500000000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS shineray_demo_activity_user_idx
    ON shineray_demo_activity(user_id, created_at DESC);

-- Existing simulated records are preserved, but never used as financial data.
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS referral_code VARCHAR(10)
    NOT NULL DEFAULT upper(substr(md5(random()::text), 1, 10));
CREATE UNIQUE INDEX IF NOT EXISTS shineray_users_referral_idx ON shineray_users(referral_code);
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS referred_by BIGINT
    REFERENCES shineray_users(id);

CREATE TABLE IF NOT EXISTS shineray_wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    provider VARCHAR(20) NOT NULL CHECK (provider IN ('TOGOCEL')),
    phone VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, provider, phone)
);

ALTER TABLE shineray_wallets ADD COLUMN IF NOT EXISTS holder_name VARCHAR(120) NOT NULL DEFAULT '';

-- Verified payment writers, authorized administration and signup bonuses only.
CREATE TABLE IF NOT EXISTS shineray_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id),
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('recharge','withdrawal','purchase','commission','bonus')),
    label VARCHAR(80) NOT NULL,
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa <> 0),
    provider_reference VARCHAR(160) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS shineray_transactions_user_idx
    ON shineray_transactions(user_id, created_at DESC);

-- Optional receipt/product facts supplied only by a verified server-side writer.
-- Missing facts remain unknown; they are not inferred from advertised returns.
ALTER TABLE shineray_transactions ADD COLUMN IF NOT EXISTS details JSONB
    NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object');

ALTER TABLE shineray_transactions DROP CONSTRAINT IF EXISTS shineray_transactions_kind_check;
ALTER TABLE shineray_transactions ADD CONSTRAINT shineray_transactions_kind_check
    CHECK (kind IN ('recharge','withdrawal','purchase','commission','bonus'));

-- No account is promoted automatically. Administrator access must be explicit.
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS shineray_deposit_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id),
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa BETWEEN 500 AND 500000000),
    provider_reference VARCHAR(120) NOT NULL UNIQUE,
    approval_method VARCHAR(12) NOT NULL CHECK (approval_method IN ('manual', 'automatic')),
    approved_by BIGINT REFERENCES shineray_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((approval_method = 'manual' AND approved_by IS NOT NULL)
        OR (approval_method = 'automatic' AND approved_by IS NULL))
);
CREATE TABLE IF NOT EXISTS shineray_first_deposits (
    user_id BIGINT PRIMARY KEY REFERENCES shineray_users(id),
    deposit_id BIGINT NOT NULL UNIQUE REFERENCES shineray_deposit_approvals(id)
);

-- Imported administration compatibility. No imported startup migrations or seeds.
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS is_banned BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS is_blocked BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS withdrawals_disabled BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS shineray_admin_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    customer_session_hash CHAR(64) NOT NULL REFERENCES shineray_sessions(token_hash) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS shineray_admin_login_attempts (
    user_id BIGINT PRIMARY KEY REFERENCES shineray_users(id) ON DELETE CASCADE,
    failures INTEGER NOT NULL DEFAULT 0,
    window_start TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_until TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS shineray_admin_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(24) NOT NULL CHECK (kind IN ('product','gift_code','channel','announcement')),
    value JSONB NOT NULL CHECK (jsonb_typeof(value) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS shineray_admin_resources_kind_idx
    ON shineray_admin_resources(kind, id);
CREATE UNIQUE INDEX IF NOT EXISTS shineray_admin_gift_code_idx
    ON shineray_admin_resources((value->>'code')) WHERE kind='gift_code';

CREATE TABLE IF NOT EXISTS shineray_admin_operations (
    request_id VARCHAR(120) PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES shineray_users(id),
    user_id BIGINT NOT NULL REFERENCES shineray_users(id),
    operation_type VARCHAR(24) NOT NULL,
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa > 0),
    result JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS shineray_admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES shineray_users(id),
    event_type VARCHAR(40) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS shineray_admin_vip_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(120) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id),
    admin_id BIGINT NOT NULL REFERENCES shineray_users(id),
    product_id BIGINT NOT NULL REFERENCES shineray_admin_resources(id),
    product_snapshot JSONB NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','revoked')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);

-- Dedicated console principal: no customer account is created or promoted.
CREATE TABLE IF NOT EXISTS shineray_console_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS shineray_console_login_attempts (
    client_hash CHAR(64) PRIMARY KEY,
    failures INTEGER NOT NULL DEFAULT 0,
    window_start TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_until TIMESTAMPTZ
);
-- NULL actor denotes the dedicated console; old account-linked history remains.
ALTER TABLE shineray_admin_operations ALTER COLUMN admin_id DROP NOT NULL;
ALTER TABLE shineray_admin_audit ALTER COLUMN admin_id DROP NOT NULL;
ALTER TABLE shineray_admin_vip_grants ALTER COLUMN admin_id DROP NOT NULL;
ALTER TABLE shineray_deposit_approvals ADD COLUMN IF NOT EXISTS approved_console BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE shineray_deposit_approvals DROP CONSTRAINT IF EXISTS shineray_deposit_approvals_check;
ALTER TABLE shineray_deposit_approvals ADD CONSTRAINT shineray_deposit_approvals_check CHECK (
    (approval_method='manual' AND
        ((approved_by IS NOT NULL AND NOT approved_console) OR (approved_by IS NULL AND approved_console)))
    OR (approval_method='automatic' AND approved_by IS NULL AND NOT approved_console)
);
