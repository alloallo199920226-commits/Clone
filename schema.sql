CREATE TABLE IF NOT EXISTS shineray_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(16) NOT NULL UNIQUE,
    password_salt BYTEA NOT NULL,
    password_hash BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT shineray_phone_format CHECK (
        phone ~ '^\+225[0-9]{10}$' OR phone ~ '^\+228[0-9]{8}$'
    )
);

CREATE TABLE IF NOT EXISTS shineray_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS shineray_sessions_user_idx
    ON shineray_sessions(user_id);

CREATE TABLE IF NOT EXISTS shineray_demo_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('recharge', 'withdrawal', 'purchase')),
    label VARCHAR(80) NOT NULL,
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa > 0 AND amount_fcfa <= 500000000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS shineray_demo_activity_user_idx
    ON shineray_demo_activity(user_id, created_at DESC);

-- Existing simulated records are preserved, but never used as financial data.
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS referral_code VARCHAR(10)
    NOT NULL DEFAULT upper(substr(md5(random()::text), 1, 10));
CREATE UNIQUE INDEX IF NOT EXISTS shineray_users_referral_idx ON shineray_users(referral_code);
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS referred_by BIGINT
    REFERENCES shineray_users(id);

CREATE TABLE IF NOT EXISTS shineray_wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id) ON DELETE CASCADE,
    provider VARCHAR(20) NOT NULL CHECK (provider IN ('TOGOCEL')),
    phone VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, provider, phone)
);

ALTER TABLE shineray_wallets ADD COLUMN IF NOT EXISTS holder_name VARCHAR(120) NOT NULL DEFAULT '';

-- Verified payment writers, authorized administration and signup bonuses only.
CREATE TABLE IF NOT EXISTS shineray_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id),
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('recharge','withdrawal','purchase','commission','bonus')),
    label VARCHAR(80) NOT NULL,
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa <> 0),
    provider_reference VARCHAR(160) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS shineray_transactions_user_idx
    ON shineray_transactions(user_id, created_at DESC);

-- Optional receipt/product facts supplied only by a verified server-side writer.
-- Missing facts remain unknown; they are not inferred from advertised returns.
ALTER TABLE shineray_transactions ADD COLUMN IF NOT EXISTS details JSONB
    NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object');

ALTER TABLE shineray_transactions DROP CONSTRAINT IF EXISTS shineray_transactions_kind_check;
ALTER TABLE shineray_transactions ADD CONSTRAINT shineray_transactions_kind_check
    CHECK (kind IN ('recharge','withdrawal','purchase','commission','bonus'));

-- No account is promoted automatically. Administrator access must be explicit.
ALTER TABLE shineray_users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS shineray_deposit_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES shineray_users(id),
    amount_fcfa BIGINT NOT NULL CHECK (amount_fcfa BETWEEN 500 AND 500000000),
    provider_reference VARCHAR(120) NOT NULL UNIQUE,
    approval_method VARCHAR(12) NOT NULL CHECK (approval_method IN ('manual', 'automatic')),
    approved_by BIGINT REFERENCES shineray_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((approval_method = 'manual' AND approved_by IS NOT NULL)
        OR (approval_method = 'automatic' AND approved_by IS NULL))
);
CREATE TABLE IF NOT EXISTS shineray_first_deposits (
    user_id BIGINT PRIMARY KEY REFERENCES shineray_users(id),
    deposit_id BIGINT NOT NULL UNIQUE REFERENCES shineray_deposit_approvals(id)
);
